using ForMatthias.Core;

namespace ForMatthias.Workspaces;

public sealed record InputSelection(string Input, string Root, string? ProjectPath, string? SingleFile)
{
    public bool IsProject => ProjectPath is not null;
}

public static class Discovery
{
    private static readonly string[] ProjectExtensions = [".csproj", ".sln", ".slnx"];
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".generated.cs", ".Designer.cs"];

    public static IEnumerable<string> Scan(string root, string pattern, bool includeOutputs = false)
    {
        // Directory symlinks are opaque during recursive scanning, preventing escapes and cycles.
        return Directory.EnumerateFiles(root, pattern, new EnumerationOptions
        {
            RecurseSubdirectories = true,
            AttributesToSkip = FileAttributes.ReparsePoint,
            IgnoreInaccessible = false
        }).Where(path => !Path.GetRelativePath(root, path).Split(Path.DirectorySeparatorChar).Any(p => p == ".git" || !includeOutputs && p is "bin" or "obj"));
    }

    public static InputSelection Select(string input, string mode)
    {
        input = Path.GetFullPath(input);
        if (!File.Exists(input) && !Directory.Exists(input)) { throw new OrganizerException(3, "CSORG5001", $"Input does not exist: {input}"); }
        if (File.Exists(input))
        {
            var ext = Path.GetExtension(input).ToLowerInvariant();
            if (ext == ".cs")
            {
                if (mode != "project") { return new(input, Path.GetDirectoryName(input)!, null, input); }
                for (var dir = new DirectoryInfo(Path.GetDirectoryName(input)!); dir is not null; dir = dir.Parent)
                {
                    var projects = dir.GetFiles("*.csproj");
                    if (projects.Length == 1) { return new(input, dir.FullName, projects[0].FullName, input); }
                    if (projects.Length > 1) { break; }
                }
                throw new OrganizerException(3, "CSORG5001", "Cannot locate an unambiguous containing project.");
            }
            if (!ProjectExtensions.Contains(ext, StringComparer.Ordinal)) { throw new OrganizerException(2, "CSORG1002", "Expected .cs, directory, .csproj, .sln, or .slnx."); }
            return new(input, Path.GetDirectoryName(input)!, mode == "syntax" ? null : input, null);
        }
        if (mode == "syntax") { return new(input, input, null, null); }
        var candidates = Scan(input, "*").Where(path => Path.GetExtension(path) is ".sln" or ".slnx").ToArray();
        if (candidates.Length == 0) { candidates = Scan(input, "*.csproj").ToArray(); }
        if (candidates.Length > 1) { throw new OrganizerException(3, "CSORG5001", "Multiple candidate solutions/projects; select an explicit path."); }
        if (candidates.Length == 0 && mode == "project") { throw new OrganizerException(3, "CSORG5001", "No project or solution found."); }
        return new(input, input, candidates.SingleOrDefault(), null);
    }

    public static bool Included(string path, string root, string text, EffectiveConfig config, bool includeGenerated, IReadOnlyList<string> includes, IReadOnlyList<string> excludes)
    {
        var relative = Path.GetRelativePath(root, path).Replace('\\', '/');
        bool Matches(string pattern) => Globs.Match(relative, pattern) || (!pattern.Contains('/') && Globs.Match(Path.GetFileName(path), pattern));
        if (includes.Count > 0 && !includes.Any(Matches)) { return false; }
        if (excludes.Concat(config.Strings("exclusions")).Any(Matches)) { return false; }
        if (includeGenerated) { return true; }
        var name = Path.GetFileName(path);
        return !relative.Split('/').Any(p => p is "bin" or "obj")
            && !GeneratedSuffixes.Any(s => name.EndsWith(s, StringComparison.OrdinalIgnoreCase))
            && !text[..Math.Min(2048, text.Length)].Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }
}
